package ua.zwf.api.tip;

/** Який текст показати в банері «Розумна порада дня» (тексти — у packages/i18n). */
public enum TipKind {

	/** Є продукти, що закінчуються протягом 24 годин: «Приготуйте … сьогодні». */
	USE_SOON,
	/** Термінових немає, але є прострочені: «Перевірте й спишіть». */
	EXPIRED,
	/** Усе свіже. */
	ALL_FRESH,
	/** Холодильник порожній: «Додайте перший продукт». */
	EMPTY

}
