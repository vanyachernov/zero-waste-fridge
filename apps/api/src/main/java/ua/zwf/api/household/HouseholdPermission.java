package ua.zwf.api.household;

/** Дії з матриці «Ролі та права доступу» (макет «Моя сім'я»). */
public enum HouseholdPermission {

	/** Переглядати холодильник і терміни придатності. */
	VIEW_FRIDGE,
	/** Додавати, редагувати та списувати продукти. */
	EDIT_PRODUCTS,
	/** Генерувати рецепти з продуктів. */
	GENERATE_RECIPES,
	/** Вести спільний список покупок. */
	SHOPPING_LIST,
	/** Отримувати нагадування про критичні терміни. */
	RECEIVE_REMINDERS,
	/** Запрошувати та видаляти учасників. */
	MANAGE_MEMBERS,
	/** Змінювати ролі учасників. */
	CHANGE_ROLES,
	/** Видаляти холодильник і всі дані. */
	DELETE_HOUSEHOLD,
	/** Перейменувати сім'ю — у макеті окремого рядка немає, тож лише власник, як і інше керування. */
	RENAME_HOUSEHOLD

}
